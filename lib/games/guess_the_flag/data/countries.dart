/// One entry in the Guess The Flag deck.
class Country {
  const Country(this.name, this.code, this.colors);

  /// Country name, as printed on the answer buttons.
  final String name;

  /// ISO 3166-1 alpha-2 code in lower case, used to build the emoji flag.
  final String code;

  /// Flag colours in the order they appear on the flag; the first two drive
  /// the card gradient.
  final List<Color> colors;

  /// Regional-indicator emoji built from [code], e.g. 'bd' renders the
  /// Bangladesh flag.
  String get flagEmoji => String.fromCharCodes(
        code.toUpperCase().codeUnits.map((c) => c + 127397),
      );
}

