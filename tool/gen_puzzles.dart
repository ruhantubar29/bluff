// Generates lib/games/chess/core/data/puzzle_data.dart.
//
// Positions come from real opening-book lines followed by tactical,
// capture/check-biased play. Four detectors extract puzzles:
//   * checkmate in 1
//   * forced checkmate in 2 (checking first, every reply is met)
//   * knight fork (every reply loses at least a minor piece)
//   * hanging piece (a loose piece worth >= 3 can be taken safely)
//
// Every candidate line is replayed through the rules engine before it is
// written, so the emitted dataset can only ever contain legal sequences.
//
// Usage:
//   dart run tool/gen_puzzles.dart
//
// Deterministic: the same seed always produces the same file.

import 'dart:io';
import 'dart:math';

import 'package:bluff/games/chess/core/chess_game.dart';
import 'package:bluff/games/chess/core/models/puzzle.dart';
import 'package:bluff/games/chess/core/openings/opening_book.dart';

const _outPath = 'lib/games/chess/core/data/puzzle_data.dart';
const _seed = 20260203;

/// Quotas per detector — generation stops once all are met.
const _quota = {
  'mate1': 14,
  'mate2': 10,
  'fork': 18,
  'hanging': 22,
};

void main() {
  final rng = Random(_seed);
  final found = <String, _Found>{}; // keyed by FEN (one puzzle per position)

  var games = 0;
  outer:
  for (var g = 0; g < 900; g++) {
    games++;
    final game = ChessGame();

    // Realistic opening phase from the book (SAN matched against legal moves).
    final line = OpeningBook.lines[rng.nextInt(OpeningBook.lines.length)];
    for (final san in line.moves) {
      LegalMove? chosen;
      for (final m in game.legalMoves) {
        if (_normalize(m.san) == _normalize(san)) {
          chosen = m;
          break;
        }
      }
      if (chosen == null) break;
      game.makeMove(
        from: chosen.from,
        to: chosen.to,
        promotion: chosen.promotion,
      );
      if (game.isGameOver) break;
    }

    // Tactical phase: biased random play, scanning every position.
    var plies = 0;
    while (!game.isGameOver && plies < 44) {
      _scan(game, found);
      if (_quotasMet(found)) break outer;

      final moves = game.legalMoves;
      if (moves.isEmpty) break;

      // Prefer captures and checks so tactics keep appearing.
      final weights = <int>[];
      var total = 0;
      for (final m in moves) {
        var w = 1;
        if (m.isCapture) w += 3;
        if (m.san.contains('+') || m.san.contains('#')) w += 3;
        weights.add(w);
        total += w;
      }
      var pick = rng.nextInt(total);
      var chosen = moves.last;
      for (var i = 0; i < moves.length; i++) {
        pick -= weights[i];
        if (pick < 0) {
          chosen = moves[i];
          break;
        }
      }
      game.makeMove(
        from: chosen.from,
        to: chosen.to,
        promotion: chosen.promotion,
        autoQueen: true,
      );
      plies++;
    }
  }

  if (found.length < 60) {
    stderr.writeln(
      'only ${found.length} puzzles found after $games games — widen play',
    );
    exit(1);
  }

  final puzzles = _finalize(found, rng);
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_puzzles.dart — do not edit by hand.')
    ..writeln('//')
    ..writeln('// Positions originate from opening-book lines; every solution')
    ..writeln('// line was replayed through the rules engine during generation')
    ..writeln('// and is re-validated in test/chess/puzzle_data_test.dart.')
    ..writeln()
    ..writeln("import '../models/puzzle.dart';")
    ..writeln()
    ..writeln('/// Curated tactical positions used by the puzzle trainer.')
    ..writeln('class PuzzleData {')
    ..writeln('  const PuzzleData._();')
    ..writeln()
    ..writeln('  /// All puzzles, ordered by rating.');

  buffer.writeln('  static const List<ChessPuzzle> puzzles = [');
  for (final p in puzzles) {
    final themes = p.themes.map((t) => "'$t'").join(', ');
    final solution = p.solution.map((s) => "'$s'").join(', ');
    buffer.writeln('    ChessPuzzle(');
    buffer.writeln("      id: '${p.id}',");
    buffer.writeln("      fen: '${p.fen}',");
    buffer.writeln('      solution: [$solution],');
    buffer.writeln('      rating: ${p.rating},');
    buffer.writeln('      themes: [$themes],');
    if (p.mateIn != null) buffer.writeln('      mateIn: ${p.mateIn},');
    buffer.writeln("      source: 'Bluff Tactics',");
    buffer.writeln("      comment: '${p.comment}',");
    buffer.writeln('    ),');
  }
  buffer.writeln('  ];');
  buffer.writeln('}');

  File(_outPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(buffer.toString());

  final counts = <String, int>{};
  for (final p in puzzles) {
    final kind = p.mateIn == 1
        ? 'mate1'
        : p.mateIn == 2
            ? 'mate2'
            : p.themes.contains('fork')
                ? 'fork'
                : 'hanging';
    counts[kind] = (counts[kind] ?? 0) + 1;
  }
  stdout.writeln(
    'wrote ${puzzles.length} puzzles to $_outPath ($games games) $counts',
  );
}

// ---------------------------------------------------------------- detection

void _scan(ChessGame game, Map<String, _Found> found) {
  final fen = game.fen;
  if (found.containsKey(fen)) return;

  if (_count(found, 'mate1') < _quota['mate1']! + 6) {
    final mate1 = _detectMate1(game, fen);
    if (mate1 != null) {
      found[fen] = mate1;
      return;
    }
  }

  if (_count(found, 'mate2') < _quota['mate2']! + 4) {
    final mate2 = _detectMate2(game, fen);
    if (mate2 != null) {
      found[fen] = mate2;
      return;
    }
  }

  if (_count(found, 'fork') < _quota['fork']! + 6) {
    final fork = _detectFork(game, fen);
    if (fork != null) {
      found[fen] = fork;
      return;
    }
  }

  if (_count(found, 'hanging') < _quota['hanging']! + 6) {
    final hanging = _detectHanging(game, fen);
    if (hanging != null) found[fen] = hanging;
  }
}

int _count(Map<String, _Found> found, String kind) {
  var n = 0;
  for (final f in found.values) {
    if (f.kind == kind) n++;
  }
  return n;
}

bool _quotasMet(Map<String, _Found> found) {
  for (final entry in _quota.entries) {
    if (_count(found, entry.key) < entry.value) return false;
  }
  return true;
}

ChessGame _clone(ChessGame game) => ChessGame(fen: game.fen);

bool _isMate(ChessGame g) => g.legalMoves.isEmpty && g.inCheck;

ChessGame? _apply(ChessGame game, LegalMove move) {
  final probe = _clone(game);
  final attempt = probe.makeMove(
    from: move.from,
    to: move.to,
    promotion: move.promotion,
  );
  if (!attempt.played) return null;
  return probe;
}

/// Checkmate in one.
_Found? _detectMate1(ChessGame game, String fen) {
  for (final m in game.legalMoves) {
    final probe = _apply(game, m);
    if (probe == null) continue;
    if (!_isMate(probe)) {
      if (probe.isGameOver) continue; // stalemate / draw: not a puzzle
      continue;
    }

    final themes = <String>['checkmate'];
    final matingPiece = _pieceAtFen(fen, m.from);
    final matedKing = _kingSquare(probe, white: !game.whiteToMove);
    if ((matingPiece == 'r' || matingPiece == 'q') &&
        matedKing != null &&
        (matedKing[1] == '1' || matedKing[1] == '8') &&
        m.to[1] == matedKing[1]) {
      themes.add('backRank');
    }

    return _Found(
      kind: 'mate1',
      fen: fen,
      solution: [_uci(m)],
      mateIn: 1,
      themes: themes,
      bonusValue: 0,
    );
  }
  return null;
}

/// Forced mate in two: checking move, every reply is met by mate.
_Found? _detectMate2(ChessGame game, String fen) {
  for (final m in game.legalMoves) {
    if (!m.san.contains('+')) continue; // start with the check
    final afterCheck = _apply(game, m);
    if (afterCheck == null || afterCheck.isGameOver) continue;

    final replies = afterCheck.legalMoves;
    if (replies.isEmpty) continue;
    final chosenReply = replies.first;
    LegalMove? chosenMate;

    var forced = true;
    for (final r in replies) {
      final afterReply = _apply(afterCheck, r);
      if (afterReply == null || afterReply.isGameOver) {
        forced = false; // reply mates us or stalemates — not a puzzle
        break;
      }
      LegalMove? mate;
      for (final km in afterReply.legalMoves) {
        final probe = _apply(afterReply, km);
        if (probe != null && _isMate(probe)) {
          mate = km;
          break;
        }
      }
      if (mate == null) {
        forced = false;
        break;
      }
      if (r.from == chosenReply.from &&
          r.to == chosenReply.to &&
          r.promotion == chosenReply.promotion) {
        chosenMate = mate;
      }
    }

    if (forced && chosenMate != null) {
      return _Found(
        kind: 'mate2',
        fen: fen,
        solution: [_uci(m), _uci(chosenReply), _uci(chosenMate)],
        mateIn: 2,
        themes: const ['checkmate', 'forcedMate'],
        bonusValue: 0,
      );
    }
  }
  return null;
}

/// Knight fork: two or more valuable loose pieces, every reply loses one.
_Found? _detectFork(ChessGame game, String fen) {
  final solverIsWhite = game.whiteToMove;

  for (final m in game.legalMoves) {
    final piece = _pieceAtFen(fen, m.from);
    if (piece == null || piece.toLowerCase() != 'n') continue;

    final afterMove = _apply(game, m);
    if (afterMove == null || afterMove.isGameOver) continue;

    final oppMoves = afterMove.legalMoves;
    // The knight must survive every legal reply.
    if (oppMoves.any((o) => o.to == m.to)) continue;

    // Loose targets on knight-reachable squares, worth at least a minor.
    final targets = <String>[];
    for (final sq in _knightAttacks(m.to)) {
      final victim = _pieceAtFen(afterMove.fen, sq);
      if (victim == null) continue;
      if ((victim == victim.toUpperCase()) == solverIsWhite) continue;
      if (_value(victim) < 3) continue;
      if (oppMoves.any((o) => o.to == sq)) continue; // defended
      targets.add(sq);
    }
    if (targets.length < 2) continue;

    // Every reply must allow a knight capture worth >= 3 net.
    final chosenReply = oppMoves.first;
    LegalMove? chosenCapture;
    var holds = true;
    for (final r in oppMoves) {
      final afterReply = _apply(afterMove, r);
      if (afterReply == null || afterReply.isGameOver) {
        holds = false;
        break;
      }
      final best = _bestKnightGain(afterReply, knightFrom: m.to);
      if (best == null) {
        holds = false;
        break;
      }
      if (r.from == chosenReply.from &&
          r.to == chosenReply.to &&
          r.promotion == chosenReply.promotion) {
        chosenCapture = best;
      }
    }
    if (!holds || chosenCapture == null) continue;

    final themes = <String>['fork'];
    if (m.san.contains('+')) themes.add('check');

    final queenTarget = targets.any(
      (sq) => (_pieceAtFen(afterMove.fen, sq) ?? '').toLowerCase() == 'q',
    );

    return _Found(
      kind: 'fork',
      fen: fen,
      solution: [_uci(m), _uci(chosenReply), _uci(chosenCapture)],
      mateIn: null,
      themes: themes,
      bonusValue: queenTarget ? 250 : 0,
    );
  }
  return null;
}

/// Knight capture netting at least a minor piece after the given reply.
LegalMove? _bestKnightGain(ChessGame afterReply, {required String knightFrom}) {
  LegalMove? best;
  var bestGain = 3;

  for (final c in afterReply.legalMoves) {
    if (c.from != knightFrom || !c.isCapture) continue;
    final victim = _pieceAtFen(afterReply.fen, c.to);
    if (victim == null) continue;
    final victimValue = _value(victim);

    final afterCapture = _apply(afterReply, c);
    if (afterCapture == null) continue;
    final recaptured = afterCapture.legalMoves.any((o) => o.to == c.to);
    final gain = victimValue - (recaptured ? 3 : 0);
    if (gain >= bestGain) {
      bestGain = gain;
      best = c;
    }
  }
  return best;
}

/// A loose piece worth >= 3 that can be taken without being recaptured.
_Found? _detectHanging(ChessGame game, String fen) {
  for (final m in game.legalMoves) {
    if (!m.isCapture) continue;
    final victim = _pieceAtFen(fen, m.to);
    if (victim == null) continue;
    final victimValue = _value(victim);
    if (victimValue < 3) continue;

    final probe = _apply(game, m);
    if (probe == null) continue;
    if (_isMate(probe)) continue; // mate-in-1 detector owns this position
    if (probe.isGameOver) continue;
    // No recapture of any kind: the piece simply drops.
    if (probe.legalMoves.any((o) => o.to == m.to)) continue;

    return _Found(
      kind: 'hanging',
      fen: fen,
      solution: [_uci(m)],
      mateIn: null,
      themes: const ['hangingPiece'],
      bonusValue: victimValue * 60,
    );
  }
  return null;
}

// ------------------------------------------------------------------ helpers

String _normalize(String san) => san.replaceAll(RegExp(r'[+#?!]+$'), '');

String _uci(LegalMove m) =>
    '${m.from}${m.to}${m.isPromotion ? (m.promotion ?? 'q') : ''}';

int _value(String piece) => switch (piece.toLowerCase()) {
      'p' => 1,
      'n' => 3,
      'b' => 3,
      'r' => 5,
      'q' => 9,
      _ => 0,
    };

bool _isDigit(String ch) => ch.compareTo('0') >= 0 && ch.compareTo('9') <= 0;

/// Letter on a square from the FEN placement field (null when empty).
String? _pieceAtFen(String fen, String square) {
  final placement = fen.split(' ').first;
  const files = 'abcdefgh';
  var rank = 8;
  var file = 0;
  for (final ch in placement.split('')) {
    if (ch == '/') {
      rank--;
      file = 0;
    } else if (_isDigit(ch)) {
      file += int.parse(ch);
    } else {
      if (rank == int.parse(square[1]) && files[file] == square[0]) return ch;
      file++;
    }
  }
  return null;
}

String? _kingSquare(ChessGame game, {required bool white}) {
  final placement = game.fen.split(' ').first;
  const files = 'abcdefgh';
  var rank = 8;
  var file = 0;
  final wanted = white ? 'K' : 'k';
  for (final ch in placement.split('')) {
    if (ch == '/') {
      rank--;
      file = 0;
    } else if (_isDigit(ch)) {
      file += int.parse(ch);
    } else {
      if (ch == wanted) return '${files[file]}$rank';
      file++;
    }
  }
  return null;
}

List<String> _knightAttacks(String square) {
  final file = square.codeUnitAt(0) - 97;
  final rank = int.parse(square[1]);
  const deltas = [
    (1, 2),
    (2, 1),
    (2, -1),
    (1, -2),
    (-1, -2),
    (-2, -1),
    (-2, 1),
    (-1, 2),
  ];
  final out = <String>[];
  for (final (df, dr) in deltas) {
    final f = file + df;
    final r = rank + dr;
    if (f >= 0 && f < 8 && r >= 1 && r <= 8) {
      out.add('${String.fromCharCode(97 + f)}$r');
    }
  }
  return out;
}

// ------------------------------------------------------------------ output

class _Found {
  _Found({
    required this.kind,
    required this.fen,
    required this.solution,
    required this.mateIn,
    required this.themes,
    required this.bonusValue,
  });

  final String kind;
  final String fen;
  final List<String> solution;
  final int? mateIn;
  final List<String> themes;
  final int bonusValue;
}

String _commentFor(String kind, List<String> themes) {
  if (kind == 'mate1') {
    if (themes.contains('backRank')) return 'The back rank never moved.';
    return 'One move ends it.';
  }
  if (kind == 'mate2') return 'Check first — every reply is met.';
  if (kind == 'fork') {
    return themes.contains('check')
        ? 'Check! The knight hits two pieces at once.'
        : 'The knight hits two pieces at once.';
  }
  return 'A loose piece is free for the taking.';
}

List<ChessPuzzle> _finalize(Map<String, _Found> found, Random rng) {
  final entries = found.values.toList();

  // Shuffle deterministically so the mix is stable across the rating order.
  entries.shuffle(rng);

  final staged = <(ChessPuzzle, String)>[];
  for (final f in entries) {
    final base = switch (f.kind) {
      'mate1' => 700,
      'mate2' => 1200,
      'fork' => 1050,
      _ => 650,
    };
    final pieces = RegExp(r'[prnbqkPRNBQK]')
        .allMatches(f.fen.split(' ').first)
        .length;
    final endgame = pieces <= 10;
    final themes = [
      ...f.themes,
      if (endgame) 'endgame',
      if (f.solution.any((u) => u.length == 5)) 'promotion',
    ];
    final rating =
        (base + f.bonusValue + (endgame ? 120 : 0) + rng.nextInt(220))
            .clamp(500, 2200);

    staged.add((
      ChessPuzzle(
        id: 'placeholder',
        fen: f.fen,
        solution: f.solution,
        rating: rating,
        themes: themes,
        mateIn: f.mateIn,
        source: 'Bluff Tactics',
        comment: _commentFor(f.kind, themes),
      ),
      f.kind,
    ));
  }

  staged.sort((a, b) => a.$1.rating.compareTo(b.$1.rating));

  final reIded = <ChessPuzzle>[];
  for (var i = 0; i < staged.length; i++) {
    final p = staged[i].$1;
    reIded.add(
      ChessPuzzle(
        id: 'p${(i + 1).toString().padLeft(3, '0')}',
        fen: p.fen,
        solution: p.solution,
        rating: p.rating,
        themes: p.themes,
        mateIn: p.mateIn,
        source: p.source,
        comment: p.comment,
      ),
    );
  }
  return reIded;
}
